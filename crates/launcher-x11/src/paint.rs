/// The 8x8 bitmap for one character.
///
/// Printable ASCII (`0x20..=0x7e`) is the font's own. Latin-1 letters with
/// diacritics — `à á â ã ç é ê í ó ô õ ú` and their capitals — are built
/// by taking the base letter's glyph and OR-ing a few pixels into row 0 as
/// an accent. An 8x8 cell has no room for a faithful acute, grave, tilde
/// or cedilla, so that mark says *"this letter is accented"* rather than
/// which accent it wears; a cédille is drawn at the top with the rest for
/// the same reason. A path that is not UTF-8 is spelled with a replacement
/// character by the daemon, so for any other codepoint `?` is the honest
/// spelling here.
pub fn glyph(c: char) -> [u8; 8] {
    let cp = c as u32;
    if (0x20..=0x7e).contains(&cp) {
        return FONT[(cp - 0x20) as usize];
    }
    // Two Latin-1 punctuation marks the launcher's own lines carry: the
    // middle dot of the header's separator and the micro sign of the
    // latency label. Without them the two most-read strings in the window
    // would spell themselves with the fallback `?`.
    match cp {
        // `·` U+00B7 MIDDLE DOT: two rows in the middle of the cell.
        0xb7 => return [0x00, 0x00, 0x00, 0x18, 0x18, 0x00, 0x00, 0x00],
        // `µ` U+00B5 MICRO SIGN: the `u` glyph with its descender.
        0xb5 => {
            let mut g = FONT[(b'u' - 0x20) as usize];
            g[7] |= 0x33;
            return g;
        }
        _ => {}
    }
    if let Some(base) = latin1_base(cp) {
        let mut g = FONT[(base - 0x20) as usize];
        // A small diacritic hint in the top row: columns 3 and 4.
        g[0] |= 0x18;
        return g;
    }
    // The honest spelling of a glyph this font does not carry.
    FONT[(b'?' - 0x20) as usize]
}

/// The base ASCII letter of a Latin-1 letter with a diacritic, if it is
/// one of the ones the launcher's languages use. Uppercase Latin-1 code
/// points are below `0xe0`, and their base is the capital letter, which
/// sits `0x20` earlier in ASCII than the lowercase spelling returned by
/// the match.
fn latin1_base(cp: u32) -> Option<u8> {
    let lower: u8 = match cp {
        0xe0..=0xe3 | 0xc0..=0xc3 => b'a', // à á â ã / À Á Â Ã
        0xe7 | 0xc7 => b'c',               // ç / Ç
        0xe9 | 0xea | 0xc9 | 0xca => b'e', // é ê / É Ê
        0xed | 0xcd => b'i',               // í / Í
        0xf3..=0xf5 | 0xd3..=0xd5 => b'o', // ó ô õ / Ó Ô Õ
        0xfa | 0xda => b'u',               // ú / Ú
        _ => return None,
    };
    Some(if cp < 0xe0 { lower - 0x20 } else { lower })
}

/// A rectangle in the coordinates Xlib draws in.
///
/// The tray still draws its menu labels with the server's own
/// [`XFillRectangles`]: it is a handful of pixels next to an icon, and a
/// client-side buffer there would buy nothing.
pub use crate::x::XRectangle;

/// The lit pixels of a string, in the fallback font, as Xlib rectangles.
pub fn rectangles(s: &str, x: i32, y: i32, scale: i32) -> alloc::vec::Vec<XRectangle> {
    let scale = scale.max(1);
    let mut out = alloc::vec::Vec::new();
    for (col, ch) in s.chars().enumerate() {
        let bits = glyph(ch);
        let base_x = x + col as i32 * 8 * scale;
        for (row, bits) in bits.iter().enumerate() {
            for bit in 0..8i32 {
                if bits & (1 << bit) == 0 {
                    continue;
                }
                out.push(XRectangle {
                    x: (base_x + bit * scale) as core::ffi::c_short,
                    y: (y + row as i32 * scale) as core::ffi::c_short,
                    width: scale as core::ffi::c_ushort,
                    height: scale as core::ffi::c_ushort,
                });
            }
        }
    }
    out
}

/// Draw a string into a server-side drawable with the fallback font.
///
/// The launcher's own frames are computed in client memory (see
/// [`crate::render`]); this exists for the tray's three menu labels, which
/// are drawn once into a small window and never repainted from a buffer.
#[allow(clippy::too_many_arguments)]
pub fn text(
    display: *mut core::ffi::c_void,
    drawable: u64,
    gc: *mut core::ffi::c_void,
    x: i32,
    y: i32,
    s: &str,
    colour: u32,
    scale: i32,
) {
    let rects = rectangles(s, x, y, scale);
    if rects.is_empty() {
        return;
    }
    // SAFETY: the handles are the caller's live ones and the rectangle
    // buffer is ours and outlives the call.
    unsafe {
        crate::x::XSetForeground(display, gc, colour as core::ffi::c_ulong);
        crate::x::XFillRectangles(
            display,
            drawable,
            gc,
            rects.as_ptr(),
            rects.len() as core::ffi::c_int,
        );
    }
}
