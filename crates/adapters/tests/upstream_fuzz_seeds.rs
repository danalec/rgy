//! Regression seeds from the upstream fuzzer, fed through the vendored
//! decoders this registry links.
//!
//! The vendored trees carry upstream's code at the pinned commit, and a
//! bug upstream fixes after the pin is a bug this tree still carries
//! until the sync brings the fix in. These seeds are the ones the
//! upstream fuzzer found on the third of November of 2026; they live
//! here so the suite proves the vendored copy refuses them even on a
//! pin the fix has not reached yet -- a panic is not an answer.

use rgx_adapters_archive::brotli::{BrotliDecoder, Error};

/// A stream whose copy is shorter than the dictionary word it names: the
/// word is the longest one there is and the transform makes it longer
/// still, and the copy asks for fewer bytes than the word produced. The
/// reference encoder does not emit such a stream, and the reference
/// decoder refuses it ("corrupt input").
const COPY_SHORTER_THAN_THE_WORD: &[u8] = &[
    0x00, 0xB1, 0x03, 0x03, 0x8C, 0x75, 0x8C, 0x07, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x8C,
    0x8C, 0x8C, 0x00, 0x62, 0x72, 0x03, 0x03, 0x31, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03, 0x03,
    0x8C, 0x75, 0x00, 0x61, 0x61, 0x72, 0x32, 0x8C, 0x8C, 0x8C, 0x8C, 0x8C, 0x75, 0x8C, 0x8C, 0x8C,
    0x8C, 0x7F, 0x7F, 0x7F, 0x7F, 0x7F, 0x7E, 0x7F, 0x7F, 0x7F, 0x00, 0x28, 0x8C, 0x8C, 0x8C, 0x8C,
    0x8C, 0x75, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0x7E, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF, 0xFF,
    0xFF, 0xFF, 0xFF, 0x8C, 0x8C, 0x8C, 0x8C, 0x31,
];

#[test]
fn a_brotli_copy_shorter_than_the_word_it_names_is_refused_not_a_panic() {
    let err = match BrotliDecoder::new().decode_bounded(COPY_SHORTER_THAN_THE_WORD, 1 << 20) {
        Ok(_) => panic!("the stream is not one the format allows"),
        Err(e) => e,
    };
    assert_eq!(err, Error::Range);
}
